#!/usr/bin/env node
/* ============================================================
   generate-seo-tags.js — sisipkan tag SEO STATIS ke <head> tiap
   halaman /id/ dan /en/ · IWHM 2026
   ------------------------------------------------------------
   Kenapa statis (bukan di-inject JS): crawler non-Google (Bingbot)
   dan scraper Facebook/WhatsApp/Twitter TIDAK menjalankan JS —
   mereka hanya membaca HTML mentah. Tag rel harus ada di HTML awal.

   Dijalankan MANUAL, bukan bagian dari build/deploy:
       node scripts/generate-seo-tags.js
   Idempotent: halaman yang sudah punya blok ini dilewati.

   ⚠️  BASE_URL di bawah HARUS diperbarui saat domain resmi aktif —
   canonical statis mengunci URL absolut. Cukup ubah konstanta ini
   lalu jalankan ulang skrip (blok lama akan diganti).
   ============================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

// Satu-satunya sumber base URL untuk canonical/hreflang. GANTI saat domain final aktif.
const BASE_URL = 'https://website-iwhm-production.up.railway.app';

const ROOT = path.resolve(__dirname, '..');
const LANGS = ['id', 'en'];
const BEGIN = '  <!-- SEO: canonical + hreflang (statis; generated by scripts/generate-seo-tags.js) -->';
const END = '  <!-- /SEO -->';

function block(lang, file) {
  const canonical = `${BASE_URL}/${lang}/${file}`;
  return [
    BEGIN,
    `  <link rel="canonical" href="${canonical}">`,
    `  <link rel="alternate" hreflang="en" href="${BASE_URL}/en/${file}">`,
    `  <link rel="alternate" hreflang="id" href="${BASE_URL}/id/${file}">`,
    `  <link rel="alternate" hreflang="x-default" href="${BASE_URL}/en/${file}">`,
    END,
  ].join('\n');
}

let written = 0, skipped = 0;
for (const lang of LANGS) {
  const dir = path.join(ROOT, lang);
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.html')) continue;
    const fp = path.join(dir, file);
    let html = fs.readFileSync(fp, 'utf8');

    // Ganti blok lama kalau ada (mis. saat BASE_URL berubah); jika tidak, sisipkan.
    const existing = new RegExp(`\\n?${BEGIN.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`, 'm');
    html = html.replace(existing, '');

    const b = block(lang, file);
    // Sisipkan setelah <link rel="icon" ...> kalau ada, kalau tidak sebelum </head>.
    const iconRe = /(<link rel="icon"[^>]*>)/;
    if (iconRe.test(html)) {
      html = html.replace(iconRe, `$1\n${b}`);
    } else {
      html = html.replace(/(\s*<\/head>)/, `\n${b}$1`);
    }
    fs.writeFileSync(fp, html);
    written++;
    console.log(`  ${lang}/${file}`);
  }
}
console.log(`\nDone. Wrote ${written} pages (skipped ${skipped}). BASE_URL=${BASE_URL}`);
